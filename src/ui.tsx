/* ---- count-up number ---- */
export function Num({ v }: { v: number }) {
  const [d, setD] = useState(v), shown = useRef(v);
  useEffect(() => {
    const a = shown.current;
    if (a === v) return;
    if (window.matchMedia?.('(prefers-reduced-motion: reduce)').matches) { shown.current = v; setD(v); return; }
    const t0 = performance.now(); let raf = 0;
    const step = (t: number) => {
      const k = Math.min(1, (t - t0) / 600);
      shown.current = Math.round(a + (v - a) * (1 - Math.pow(1 - k, 3))); setD(shown.current);
      if (k < 1) raf = requestAnimationFrame(step);
    };
    raf = requestAnimationFrame(step); return () => cancelAnimationFrame(raf);
  }, [v]);
  return <>{d.toLocaleString()}</>;
}

/* ---- progress ring ---- */
export function Ring({ pct, size = 44 }: { pct: number; size?: number }) {
  const r = (size - 6) / 2, c = 2 * Math.PI * r;
  return (
    <svg className="ring" width={size} height={size} viewBox={`0 0 ${size} ${size}`} aria-hidden="true">
      <circle cx={size / 2} cy={size / 2} r={r} className="ring-bg" />
      <circle cx={size / 2} cy={size / 2} r={r} className="ring-fg" strokeDasharray={c} strokeDashoffset={c * (1 - Math.max(0, Math.min(1, pct)))} />
    </svg>
  );
}

