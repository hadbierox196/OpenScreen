/* ---- toasts ---- */
type Kind = 'ok' | 'err' | 'info';
const Ctx = createContext<(text: string, kind?: Kind) => void>(() => {});
export const useToast = () => useContext(Ctx);
export function ToastProvider({ children }: { children: ReactNode }) {
  const [ts, setTs] = useState<{ id: number; kind: Kind; text: string }[]>([]);
  const n = useRef(0);
  const push = useCallback((text: string, kind: Kind = 'ok') => {
    const id = ++n.current;
    setTs(t => [...t.slice(-3), { id, kind, text }]);
    setTimeout(() => setTs(t => t.filter(x => x.id !== id)), 4200);
  }, []);
  return (
    <Ctx.Provider value={push}>
      {children}
      <div className="toasts" role="status" aria-live="polite">
        {ts.map(t => <div key={t.id} className={`toast ${t.kind}`}><Icon n={t.kind === 'err' ? 'alert' : t.kind === 'ok' ? 'check' : 'info'} size={16} />{t.text}</div>)}
      </div>
    </Ctx.Provider>
  );
}

/* ---- modal ---- */
export function Modal({ open, onClose, title, children }: { open: boolean; onClose: () => void; title: string; children: ReactNode }) {
  useEffect(() => {
    if (!open) return;
    const h = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose(); };
    window.addEventListener('keydown', h); return () => window.removeEventListener('keydown', h);
  }, [open, onClose]);
  if (!open) return null;
  return (
    <div className="overlay" onMouseDown={e => { if (e.target === e.currentTarget) onClose(); }}>
      <div className="modal" role="dialog" aria-modal="true" aria-label={title}>
        <div className="modal-head"><h2>{title}</h2><button className="ghost icon" onClick={onClose} aria-label="Close"><Icon n="x" /></button></div>
        {children}
      </div>
    </div>
  );
}

